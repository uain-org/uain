// Disposable member/checker/relay fixture only. Never accepts a production key path.
import assert from 'node:assert/strict';
import { generateKeyPairSync, createPublicKey } from 'node:crypto';
import { spawn, spawnSync } from 'node:child_process';
import { once } from 'node:events';
import { createInterface } from 'node:readline';
import { mkdtemp, readFile, writeFile, stat } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { reviewCertificate, encryptPrivateReview, decryptPrivateReview, privatePartyConsent, signPrivateApproval } from '../client/private-review.mjs';
const fixtures = process.env.UAIN_PUBLIC_FIXTURE_DIR;
const wallet = process.argv[2];
if (!fixtures || !wallet) throw new Error('disposable public Orchard fixtures and wallet binary required');
const root = await mkdtemp(join(tmpdir(), 'uain-private-wallet-smoke-'));
const senderKeyFile = join(root, 'fictional-sender-key');
await writeFile(senderKeyFile, Buffer.alloc(32, 1), { mode: 0o600, flag: 'wx' });
const receive = spawnSync(wallet, ['keygen', join(root, 'fictional-receiver-key')], { encoding: 'utf8' });
assert.equal(receive.status, 0, receive.stderr);
const receiverAddress = JSON.parse(receive.stdout).address;
assert.equal((await stat(join(root, 'fictional-receiver-key'))).mode & 0o777, 0o600);
assert.notEqual(spawnSync(wallet, ['keygen', join(root, 'fictional-receiver-key')]).status, 0, 'wallet key overwritten');
const reviewer = generateKeyPairSync('ed25519'); const encryption = generateKeyPairSync('x25519');
const relay = generateKeyPairSync('ed25519');
const sender = generateKeyPairSync('ed25519'); const receiver = generateKeyPairSync('ed25519');
const raw = key => Buffer.from((key.type === 'public' ? key : createPublicKey(key)).export({ type: 'spki', format: 'der' })).subarray(-32).toString('hex');
const deposit = await readFile(join(fixtures, 'deposit.bin'));
const commitments = [0, 1].map(i => deposit.subarray(45 + i * 884 + 96, 45 + i * 884 + 128).toString('hex'));
const position = Number(await readFile(join(fixtures, 'deposit-owned-position.txt'), 'utf8'));
const reviewFile = join(root, 'fictional-private-review.json');
const client = spawn(wallet, ['pay'], { stdio: ['pipe', 'pipe', 'pipe'] });
let stderr = ''; client.stderr.on('data', data => { stderr += data; });
const lines = createInterface({ input: client.stdout })[Symbol.asyncIterator]();
const closed = once(client, 'close');
const intent = { chain_id: 'uain-test-1', expires_height: 400, licence_revision: '0', expected_root: (await readFile(join(fixtures, 'deposit-anchor.hex'), 'utf8')).trim(), key_file: senderKeyFile, commitments, source_bundle: deposit.toString('hex'), source_position: position, recipient: receiverAddress, amount: 26, purpose_commitment: '09'.repeat(32), reviewer_public_key: raw(reviewer.publicKey), memo: 'fictional neutral compute trade', review_file: reviewFile };
const badReview = join(root, 'fictional-wrong-root-review.json');
const badRoot = spawnSync(wallet, ['pay'], { encoding: 'utf8', input: JSON.stringify({ ...intent, expected_root: '00'.repeat(32), review_file: badReview }) + '\n', timeout: 15000 });
assert.equal(badRoot.status, 1, 'unverified witness root accepted');
assert.equal(badRoot.stdout, '');
assert.match(badRoot.stderr, /Private wallet operation refused/);
await assert.rejects(readFile(badReview), { code: 'ENOENT' });
client.stdin.write(JSON.stringify(intent) + '\n');
const request = JSON.parse((await lines.next()).value);
assert.equal((await stat(reviewFile)).mode & 0o777, 0o600);
const packet = JSON.parse(await readFile(reviewFile, 'utf8'));
const context = { version: 1, chain: 'uain-test-1', expires: String(request.expires_height), licenceRevision: request.licence_revision, effects: request.effects, purpose: request.purpose_commitment, reviewer: raw(reviewer.publicKey) };
const certificate = reviewCertificate(context, encryption.publicKey, reviewer.privateKey);
const encrypted = encryptPrivateReview({ certificate, trustedReviewerPublicKey: reviewer.publicKey, currentHeight: 4, chain: context.chain, packet });
assert.ok(!JSON.stringify(encrypted).includes(packet.one_time_viewing_key));
const recovered = decryptPrivateReview({ envelope: encrypted, reviewerEncryptionKey: encryption.privateKey, trustedReviewerPublicKey: reviewer.publicKey, currentHeight: 4, chain: context.chain });
const checkerFile = join(root, 'fictional-checker-review.json');
await writeFile(checkerFile, JSON.stringify(recovered), { mode: 0o600, flag: 'wx' });
const inspection = spawnSync(wallet, ['inspect-review', checkerFile], { encoding: 'utf8' });
assert.equal(inspection.status, 0, inspection.stderr);
const inspected = JSON.parse(inspection.stdout);
assert.equal(inspected.effects, context.effects);
assert.ok(inspected.outputs.some(output => output.address === receiverAddress && output.amount === '26'));
const change = inspected.outputs.find(output => output.amount === '44'); assert.ok(change);
const senderConsent = privatePartyConsent(context, change.address, sender.privateKey);
const recipientConsent = privatePartyConsent(context, receiverAddress, receiver.privateKey);
const approval = signPrivateApproval({ context, reviewerSigningKey: reviewer.privateKey, sender: senderConsent, recipient: recipientConsent, licensedSenderKey: sender.publicKey, licensedRecipientKey: receiver.publicKey, trustedRelayerKey: relay.publicKey, outputs: inspected.outputs, amount: '26', decision: { class: 'neutral', checkedPurpose: context.purpose, bothLicencesChecked: true, statement: 'The fixture reviewer checked both fictional licences and the private compute agreement.' } });
client.stdin.end(JSON.stringify({ effects: approval.effects, purpose_commitment: approval.purpose_commitment, class: approval.class, expires_height: Number(approval.expires_height), licence_revision: approval.licence_revision, signature: Buffer.from(approval.signature, 'base64url').toString('hex') }) + '\n');
const result = JSON.parse((await lines.next()).value);
const [exit] = await closed; assert.equal(exit, 0, stderr);
assert.equal(Buffer.from(result.bundle_hex, 'hex').readBigInt64LE(5), 0n);
assert.ok(!result.bundle_hex.includes(receiverAddress));
const receipt = { pass: true, fixture_directory: root, wallet_keys_created_privately: true, overwrite_refused: true, checker_transport_encrypted: true, one_time_viewing_key_used: true, both_party_consents_checked: true, checker_recovered_matching_outputs: true, wallet_generated_and_verified_proof: true, value_balance: '0', fixture_only: true };
await writeFile(join(root, 'receipt.json'), JSON.stringify(receipt, null, 2) + '\n', { mode: 0o600 });
// Transfer only the public final fixture bundle/approval for additional native checks.
await writeFile(join(fixtures, 'wallet-payment.bin'), Buffer.from(result.bundle_hex, 'hex'));
await writeFile(join(fixtures, 'wallet-approval.json'), JSON.stringify(approval));
await writeFile(join(fixtures, 'wallet-reviewer-public-key.hex'), raw(reviewer.publicKey));
console.log(JSON.stringify(receipt));
