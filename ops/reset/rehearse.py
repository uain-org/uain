#!/usr/bin/env python3
"""Actual DB archive/restore/stage/activation and two native nodes, test-only."""
import hashlib
import io
import json
import os
from pathlib import Path
import subprocess
import tempfile
import time
import urllib.request
import archive
import database
import native
import stack

# The runner supplies a separate test-only PostgreSQL and fixture schema.
source=os.environ['UAIN_RESET_FIXTURE_DB']
if not source.startswith('uain_reset_fixture_') or os.environ.get('UAIN_RESET_TEST')!='1':
    raise SystemExit('Rehearsal requires an isolated fixture database')
epoch=os.environ['UAIN_RESET_FIXTURE_EPOCH']
binary=Path(os.environ['UAIN_RESET_FIXTURE_BINARY'])
key='ab'*32  # public fixture key; never used for production
root=Path(os.environ['UAIN_RESET_FIXTURE_ROOT'])
root.mkdir(mode=0o700)
database.sql(source,'CREATE TABLE IF NOT EXISTS reset_public_records (path text PRIMARY KEY,payload jsonb); CREATE TABLE IF NOT EXISTS reset_reserved_ids (kind text,record_id text,PRIMARY KEY(kind,record_id));')
expected=database.plan(source,epoch)
original=expected['before']
archive_path=root/'database.resetbk'
process=subprocess.Popen(['pg_dump','-Fc',source],stdout=subprocess.PIPE,stderr=subprocess.DEVNULL)
receipt=archive.seal(process.stdout,archive_path,key)
assert process.wait()==0
recovered='uain_recovered_'+epoch
database.sql('postgres','CREATE DATABASE '+database.identifier(recovered)+' TEMPLATE template0;')
restore=subprocess.Popen(['pg_restore','--exit-on-error','--no-owner','-d',recovered],stdin=subprocess.PIPE,stderr=subprocess.DEVNULL)
archive.open_verified(archive_path,key,restore.stdin);restore.stdin.close();assert restore.wait()==0
snapshot=database.snapshot(recovered)
assert snapshot['tables']==original['tables'] and snapshot['hashes']==original['hashes']
# Same-count modifications must invalidate a reviewed plan.
database.sql(source,"UPDATE members SET name='modified' WHERE id=1;")
try:database.stage(expected)
except ValueError:pass
else:raise AssertionError('same-count stale plan accepted')
database.sql(source,"UPDATE members SET name='fixture' WHERE id=1;")
assert database.plan(source,epoch)==expected
staged=database.stage(expected);assert staged['source_unchanged'] and staged['active_rows']==0
activated=database.activate(expected)
assert database.snapshot(source)['head']==original['head']
after=database.snapshot(source)
assert all(after['tables'][name]==0 for name in expected['clear'])
# Actual daemon initialization uses a fictional public guardian generated by the existing smoke helper.
old=json.loads(Path(os.environ['UAIN_RESET_FIXTURE_GENESIS']).read_text())
legacy={'manifest_digest':expected['digest'],'ledger_head':original['head']['hash'],'last_event_id':original['head']['id'],
        'pinned_public_key':'fictional-isolated-ledger-public-key'}
state=native.fresh_state(old,legacy,{'chain_id':old['chain_id'],'guardians':old['app_state']['guardians'],'members':old['app_state']['members']})
home_a=root/'app';home_b=root/'db'
genesis=native.initialize(binary,home_a,'uain-reset-fixture-'+epoch,state,'tcp://127.0.0.1:27677','tcp://127.0.0.1:27676')
native.initialize(binary,home_b,genesis['chain_id'],state,'tcp://127.0.0.1:27687','tcp://127.0.0.1:27686')
native.set_fullnode(home_b,genesis,native.identity(home_a)+'@127.0.0.1:27676')
processes=[]
def rpc(port,path):
    with urllib.request.urlopen(f'http://127.0.0.1:{port}/{path}',timeout=5) as response:return json.load(response)['result']
try:
    for home in [home_a,home_b]:
        out=(root/(home.name+'.log')).open('wb');processes.append(subprocess.Popen([str(binary),'start','--home',str(home)],stdout=out,stderr=out))
    for attempt in range(60):
        try:
            a=rpc(27677,'status');b=rpc(27687,'status')
            if min(int(a['sync_info']['latest_block_height']),int(b['sync_info']['latest_block_height']))>=3:break
        except Exception:pass
        time.sleep(0.5)
    else:raise AssertionError('New nodes did not commit')
    height=min(int(a['sync_info']['latest_block_height']),int(b['sync_info']['latest_block_height']))-1
    block_a=rpc(27677,'commit?height='+str(height));block_b=rpc(27687,'commit?height='+str(height))
    assert block_a['signed_header']==block_b['signed_header']
    assert a['node_info']['network']==b['node_info']['network']==genesis['chain_id']
    assert a['validator_info']['voting_power']=='10' and b['validator_info']['voting_power']=='0'
finally:
    for process in processes:process.terminate()
    for process in processes:process.wait(timeout=20)
# Real stopped node archive and a complete authenticated tree restore.
chain=root/'node.resetbk'
pack=subprocess.Popen(['tar','-czf','-','-C',str(root),'app'],stdout=subprocess.PIPE,stderr=subprocess.DEVNULL)
chain_receipt=archive.seal(pack.stdout,chain,key);assert pack.wait()==0
archive.unpack(chain,key,root/'restored-node')
assert stack.tree_hash(home_a)==stack.tree_hash(root/'restored-node/app')
result={'database_archive_authenticated':True,'database_restore_matches':True,'same_count_stale_plan_refused':True,
 'staged_active_rows':0,'database_activated':activated,'history_preserved':True,'two_node_state_agrees':True,
 'fresh_chain_id':genesis['chain_id'],'signer_power':10,'fullnode_power':0,'native_archive_restore_matches':True,
 'database_archive':receipt,'node_archive':chain_receipt,'production_reset':False}
(root/'receipt.json').write_text(json.dumps(result,indent=2)+'\n')
print(json.dumps(result))
